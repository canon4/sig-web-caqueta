#!/usr/bin/env bash
# Se ejecuta una sola vez al crear el contenedor de PostGIS (entorno Docker)
set -e
psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB" <<SQL
CREATE EXTENSION IF NOT EXISTS postgis;
CREATE ROLE ${DB_APP_USER} LOGIN PASSWORD '${DB_APP_PASS}';
GRANT CONNECT ON DATABASE ${POSTGRES_DB} TO ${DB_APP_USER};
GRANT USAGE ON SCHEMA public TO ${DB_APP_USER};
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO ${DB_APP_USER};
SQL
